var (
	labelFG = color.NRGBA{255, 255, 255, 255}
	labelBG = color.NRGBA{24, 24, 32, 215}
)

func labelRunes(text string) []rune {
	var out []rune
	for _, r := range strings.ToUpper(text) {
		if _, ok := glyphs[r]; ok {
			out = append(out, r)
		}
	}
	return out
}

const labelPad = 2

func LabelSize(text string) (w, h int) {
	rs := labelRunes(text)
	if len(rs) == 0 {
		return 0, 0
	}
	for _, r := range rs {
		w += len(glyphs[r][0]) + 1
	}
	return w - 1 + 2*labelPad, glyphH + 2*labelPad
}

func LabelPNG(text string, scale, canvasW, canvasH int) []byte {
	lw, lh := LabelSize(text)
	if lw == 0 {
		return nil
	}
	lw, lh = lw*scale, lh*scale
	img := image.NewNRGBA(image.Rect(0, 0, canvasW, canvasH))
	x0, y0 := (canvasW-lw)/2, (canvasH-lh)/2
	fill := func(x, y, w, h int, c color.NRGBA) {
		draw.Draw(img, image.Rect(x, y, x+w, y+h), image.NewUniform(c), image.Point{}, draw.Src)
	}
	fill(x0, y0, lw, lh, labelBG)
	cx, cy := x0+labelPad*scale, y0+labelPad*scale
	for _, r := range labelRunes(text) {
		g := glyphs[r]
		for gy := range glyphH {
			for gx := range len(g[gy]) {
				if g[gy][gx] == '#' {
					fill(cx+gx*scale, cy+gy*scale, scale, scale, labelFG)
				}
			}
		}
		cx += (len(g[0]) + 1) * scale
	}
	var buf bytes.Buffer
	enc := png.Encoder{CompressionLevel: png.BestSpeed}
	enc.Encode(&buf, img)
	return buf.Bytes()
}
